/**
 * Build a pipeline directive from a researched subject.
 *
 *   node tools/build-directive.mjs --from-article=<slug> [--out=data/directive.json] [--force]
 *   node tools/build-directive.mjs --from-article=<slug> --dry-run
 *
 * ## What a directive is
 *
 * The one input the cloud pipeline cannot produce for itself. `cloud-executor.mjs` refuses to write
 * without five sourced figures, and `cloud-orchestrator.mjs` refuses to pick its own subject, so
 * everything downstream depends on this file existing and being honest.
 *
 * A directive is therefore the handover point between research, which is human, and production, which
 * is not. It carries the figures with their five parts each and the bibliography, and nothing else -
 * no prose, no angle the writer has to reverse-engineer from a title.
 *
 * ## Why it is generated rather than hand-written
 *
 * Hand-writing the JSON invites a typo in a retrieval date or a dropped fifth field, and the executor's
 * first act is to reject a thin directive, so the failure would appear as "the writer refused" rather
 * than "the date was malformed". Generating it from the article that holds the verified figures keeps
 * one source of truth.
 *
 * ## The reuse warning
 *
 * Taking the figures from an article that is already published produces a directive that, if run,
 * writes a second article on a subject the site already covers. That is useful once, to prove the
 * pipeline end to end, and wrong as a habit. The tool says so on every run and marks the output.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const BLOG = join(ROOT, "src", "content", "blog");
const args = process.argv.slice(2);
const flag = (name, dflt) => {
  const hit = args.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : dflt;
};
const DRY = args.includes("--dry-run");
const FORCE = args.includes("--force");

const from = flag("from-article", null);
if (!from) {
  console.log("usage: node tools/build-directive.mjs --from-article=<slug> [--out=data/directive.json] [--force]");
  console.log("");
  console.log("  available subjects with figures:");
  for (const f of readdirSync(BLOG).filter((x) => x.endsWith(".md")).sort()) {
    const t = readFileSync(join(BLOG, f), "utf8");
    const n = (t.match(/^ {2}- value:/gm) ?? []).length;
    const draft = /^draft:\s*true/m.test(t);
    if (n >= 5 && !draft) console.log(`    ${String(n).padStart(3)} figures  ${f.replace(/\.md$/, "")}`);
  }
  process.exit(2);
}

const src = join(BLOG, `${from}.md`);
if (!existsSync(src)) {
  console.log(`  no article at ${src}`);
  process.exit(2);
}
const text = readFileSync(src, "utf8");
const fm = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text)?.[1] ?? "";
const body = text.slice(text.indexOf("\n---", 4) + 5);

/* The same five-part parser the other tools use, so a figure cannot be read one way here and
   another way there. */
function parseFigures(block) {
  const out = [];
  let cur = null;
  for (const line of block.split(/\r?\n/)) {
    const start = /^\s{2}- (\w+):\s*(.*)$/.exec(line);
    if (start) {
      if (cur) out.push(cur);
      cur = { [start[1]]: start[2].trim().replace(/^"|"$/g, "") };
      continue;
    }
    const cont = /^\s{4}(\w+):\s*(.*)$/.exec(line);
    if (cont && cur) cur[cont[1]] = cont[2].trim().replace(/^"|"$/g, "");
  }
  if (cur) out.push(cur);
  return out;
}
const figureBlock = fm.split(/^figures:\s*$/m)[1]?.split(/^\w+:/m)[0] ?? "";
const figures = parseFigures(figureBlock);
const complete = figures.filter((f) => f.value && f.unit && f.period && f.source && f.retrieved);

const sourceBlock = fm.split(/^sources:\s*$/m)[1]?.split(/^\w+:/m)[0] ?? "";
const sources = [...sourceBlock.matchAll(/^\s{2}-\s*"?(.+?)"?\s*$/gm)].map((m) => m[1].trim()).filter(Boolean);

/* The heading of "What happened" is the closest thing to a stated subject. */
const happened = /##\s*What happened\s*\n+([\s\S]{0,600}?)(?=\n##\s)/.exec(body)?.[1]?.trim() ?? "";
const topic = (/^title:\s*"?(.+?)"?\s*$/m.exec(fm)?.[1] ?? from).trim();

const directive = {
  _note:
    "Generated by tools/build-directive.mjs. This is the handover from research to production: the " +
    "figures are the only numbers the writer may use, and the bibliography is the only citation set. " +
    "Edit the angle, never the figures - a changed figure is a claim nobody verified.",
  _generated: new Date().toISOString(),
  _from_article: from,
  _reuse_warning:
    "REUSE. The figures come from an article that is already published. Running this writes a second " +
    "article on a covered subject, which is acceptable once to prove the pipeline and wrong as a habit.",
  slug: flag("slug", `${from}-v2`),
  title_idea: topic,
  keyword: (/^target_keyword:\s*"?(.+?)"?\s*$/m.exec(fm)?.[1] ?? "").trim(),
  category: (/^category:\s*"?(.+?)"?\s*$/m.exec(fm)?.[1] ?? "trade-policy").trim(),
  audience: (/^audience:\s*"?(.+?)"?\s*$/m.exec(fm)?.[1] ?? "importer").trim(),
  angle:
    flag("angle", "") ||
    "Write the follow-up that the first article could not: take the same primary documents and answer " +
    "the question a reader asked next. Do not restate the original.",
  subject_summary: happened.slice(0, 600),
  figures: complete,
  sources,
};

console.log(`DIRECTIVE from ${from}\n${"=".repeat(80)}`);
console.log(`  figures parsed   : ${figures.length}`);
console.log(`  five-part complete: ${complete.length}  ${complete.length >= 5 ? "(meets the minimum)" : "(BELOW the minimum of 5 - the writer will refuse)"}`);
console.log(`  sources          : ${sources.length}`);
console.log(`  figures missing a field: ${figures.length - complete.length}`);
for (const f of figures.filter((x) => !complete.includes(x))) {
  const missing = ["value", "unit", "period", "source", "retrieved"].filter((k) => !x[k]);
  console.log(`      value="${f.value ?? "?"}" missing: ${missing.join(", ")}`);
}

if (complete.length < 5) {
  console.log("");
  console.log("  Not writing a directive: the executor would refuse it, and a directive that cannot be");
  console.log("  used is worse than none because it looks like progress.");
  process.exit(1);
}

const out = flag("out", "data/directive.json");
if (DRY) {
  console.log(`\n  --dry-run: would write ${out}`);
  process.exit(0);
}
if (existsSync(out) && !FORCE) {
  console.log(`\n  ${out} already exists. Pass --force to overwrite.`);
  process.exit(1);
}
mkdirSync(join(ROOT, "data"), { recursive: true });
writeFileSync(join(ROOT, out), JSON.stringify(directive, null, 2), "utf8");
console.log(`\n  written: ${out}`);
console.log(`  slug   : ${directive.slug}`);
console.log(`  keyword: ${directive.keyword}`);
console.log("");
console.log("  ★ REUSE: the figures come from a published article, so a run produces a second piece on a");
console.log("    covered subject. That is fine once, to prove the pipeline, and wrong as a habit.");
