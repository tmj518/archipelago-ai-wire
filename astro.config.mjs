// @ts-check
import { defineConfig } from "astro/config";
import sitemap from "@astrojs/sitemap";

import { SITE_URL } from "./src/consts";
import sitemapLastmod from "./tools/sitemap-lastmod.mjs";

/**
 * Astro 7 static build.
 *
 * Deployment target is Cloudflare Pages (spec §2): the repo is pushed to
 * GitHub and CF Pages runs `pnpm build` -> publishes `dist/`.
 * There is deliberately no adapter — this is a fully static site.
 */
export default defineConfig({
  // Single source of truth for the domain lives in src/consts.ts.
  site: SITE_URL,
  trailingSlash: "ignore",
  /**
   * The source directory, overridable so a rehearsal can build a scratch tree.
   *
   * tools/rehearse.mjs runs the whole pipeline with the model stubbed and checks that the article it
   * produces actually passes the content schema. It cannot do that against the working tree without
   * writing a rehearsed article into the real collection, so it points `srcDir` at its scratch copy
   * instead. The default is unchanged and nothing in a normal build sets this.
   */
  srcDir: process.env.ASTRO_SRC_DIR || "./src",
  integrations: [
    sitemap({
      /*
       * Utility and legal pages, plus anything the page itself marks noindex.
       *
       * `/confirmed/` was missing from this list until 2026-10-08, which produced the exact
       * contradiction the rule exists to prevent: the page carried
       * `<meta name="robots" content="noindex">` while the sitemap handed the same URL to
       * Google. A page asking not to be indexed must not be submitted for indexing.
       *
       * The rule, rather than the instance: everything excluded here is either a legal or
       * transactional page with no search value, or a page that sets noindex on itself. When
       * a page gains noindex, it belongs in this pattern.
       */
      /*
       * Excluded only: pages that set noindex on themselves.
       *
       * /privacy/ and /confirmed/ both carry `<meta name="robots" content="noindex">`, so submitting them
       * would be the contradiction this filter exists to prevent, and they stay out.
       *
       * /contact/ was here without setting noindex and is now in the sitemap. It is a page people search for
       * by name - "Landed Math contact" - so withholding it from the one file that enumerates the site is a
       * page that asked to be found and was not offered. The rule above the filter already said an exclusion
       * is either a page with no search value or a page that says noindex; /contact/ is neither.
       */
      /*
       * /search/ joins the list because it sets noindex. It is a tool, not a document: a result page whose query
       * lives in the URL has nothing stable to index and would compete with the articles it points at.
       */
      filter: (page) => !/\/(privacy|confirmed|search)\/$/.test(page),
    }),
    /*
     * Adds a real `lastmod` to sitemap entries, derived from the content rather than from the
     * build. The sitemap carried 74 URLs and no lastmod on any of them, which is the one field
     * that tells a crawler what it cannot work out for itself. Order matters: this runs after
     * the sitemap plugin and patches its output.
     */
    sitemapLastmod(),
  ],
  markdown: {
    shikiConfig: { theme: "github-light" },
  },
  build: {
    // Emit /about/index.html style paths so URLs stay extension-less.
    format: "directory",
  },
  /**
   * Content Security Policy, generated by Astro rather than declared by hand.
   *
   * The hand-written policy in public/_headers said `script-src 'self'`, and Astro
   * inlines page scripts into the HTML by default. Every inline script was therefore
   * refused by the browser, which silently killed every interaction on the site — the
   * mobile Menu button among them. Nothing in the build, the gates or the deploy
   * reported it; it only showed up when a real browser clicked the button.
   *
   * Astro computes a hash for each script it emits and puts it in the policy, so the
   * policy and the scripts cannot drift apart. The directives below mirror the
   * hand-written policy this replaces, minus script-src which Astro supplies.
   */
  security: {
    csp: {
      algorithm: "SHA-256",
      directives: [
        "default-src 'self'",
        /* Google Analytics sends measurement as an image request when sendBeacon is unavailable. */
        "img-src 'self' data: https://www.google-analytics.com https://www.googletagmanager.com",
        "form-action 'self'",
        "base-uri 'self'",
        /*
         * Cloudflare Web Analytics sends its measurement to cloudflareinsights.com, which is a
         * different origin from the script that collects it. Without this the beacon loads and then its
         * request is refused, so the dashboard stays empty while the page looks fine - the same silent
         * failure this whole feature already suffered once when the token was missing.
         */
        "connect-src 'self' https://cloudflareinsights.com https://www.google-analytics.com https://region1.google-analytics.com https://analytics.google.com",
      ],
      /**
       * script-src and style-src are not settable in `directives`; Astro owns them
       * because it is the thing that knows the hashes.
       *
       * `resources` lists the external origins allowed here. The critical part is that Astro keeps
       * emitting the hashes for the scripts it inlines alongside them - those hashes are what makes the
       * site's own JavaScript run, mobile Menu button included, after the hand-written `script-src
       * 'self'` refused every inline script and silently killed every interaction. Adding an origin
       * here must not be allowed to drop them, so the built output is checked for both after a change:
       * the hashes are still present and the beacon is present.
       *
       * styles need one addition of their own: Shiki emits inline style attributes for syntax
       * highlighting, and `resources` does not include 'self' by default, so it is named here along
       * with the inline allowance.
       */
      scriptDirective: {
        /*
         * googletagmanager.com serves the gtag.js loader. The inline bootstrap that follows it is hashed by
         * Astro like every other inline script, so the origin alone is not enough and the hash is what
         * actually permits it - both are present in the built output and check-csp verifies that.
         */
        resources: ["'self'", "https://static.cloudflareinsights.com", "https://www.googletagmanager.com"],
      },
      styleDirective: {
        resources: ["'self'", "'unsafe-inline'"],
      },
    },
  },
});
